class Command(BaseCommand):

    help = '6分野・24テーマの基本教材を登録します。'

    @transaction.atomic
    def handle(self, *args, **options):

        created_count = 0
        existing_count = 0

        for field, materials in MATERIALS.items():

            for title, content in materials:

                _, created = (
                    LearningMaterial.objects.get_or_create(
                        field=field,
                        title=title,
                        defaults={
                            'content': content.strip(),
                            'is_active': True,
                        },
                    )
                )

                if created:
                    created_count += 1
                else:
                    existing_count += 1

        self.stdout.write(
            self.style.SUCCESS(
                f'追加: {created_count}件 / '
                f'登録済み: {existing_count}件'
            )
        )